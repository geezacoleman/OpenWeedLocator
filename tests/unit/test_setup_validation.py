        """_on_message parses topic_parts[1] as device_id."""
        topic = 'owl/owl-pi-3/state'
        parts = topic.split('/')
        assert len(parts) == 3
        assert parts[1] == 'owl-pi-3'
        assert parts[2] == 'state'


