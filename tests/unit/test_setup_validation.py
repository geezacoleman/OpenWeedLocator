        ctrl_cfg = configparser.ConfigParser()
        ctrl_cfg.read(str(ctrl_ini))
        owl1_cfg = configparser.ConfigParser()
        owl1_cfg.read(str(owl1_ini))
        owl2_cfg = configparser.ConfigParser()
        owl2_cfg.read(str(owl2_ini))

